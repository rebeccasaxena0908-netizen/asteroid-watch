"""Write the PHP dashboard's database config, outside the web root.

Apache runs as user 'daemon', which cannot read the project's .env inside the home folder, so
`make deploy` writes the read-only user's credentials to a file under XAMPP's etc/ folder instead:

    /Applications/XAMPP/xamppfiles/etc/asteroid-watch/db.ini

It holds only the read-only dashboard user (SELECT on asteroid_watch), never the NASA key or the
pipeline user's password. It is never copied into htdocs and never committed.

Usage: python -m pipeline.dashboard_config [--path PATH]
"""
import argparse
import os
from pathlib import Path

from pipeline.config import load_settings

DEFAULT_PATH = Path("/Applications/XAMPP/xamppfiles/etc/asteroid-watch/db.ini")


def ini_text(settings) -> str:
    def q(value: str) -> str:
        if '"' in value or "\n" in value:
            raise ValueError("config values must not contain quotes or newlines")
        return f'"{value}"'

    return "\n".join([
        "; Asteroid Watch dashboard database config (read-only user).",
        "; Generated by `make deploy` from the project's .env. Do not edit or commit.",
        f"socket = {q(settings.db_socket)}",
        f"host = {q(settings.db_host)}",
        f"port = {settings.db_port}",
        f"dbname = {q(settings.db_name)}",
        f"user = {q(settings.dashboard_db_user)}",
        f"password = {q(settings.dashboard_db_password)}",
        "",
    ])


def write_config(path: Path = DEFAULT_PATH) -> Path:
    settings = load_settings()
    if not settings.dashboard_db_password:
        raise SystemExit("DASHBOARD_DB_PASSWORD is empty in .env. Set it and run `make setup-db` first.")
    path.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(path.parent, 0o755)
    path.write_text(ini_text(settings))
    # Readable by Apache ('daemon' user), writable only by you. The user it contains can only SELECT.
    os.chmod(path, 0o644)
    return path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Write the dashboard DB config file")
    parser.add_argument("--path", type=Path, default=DEFAULT_PATH)
    print(f"Wrote {write_config(parser.parse_args().path)}")
